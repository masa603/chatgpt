"""Build matching Dense/CSR data and frozen-input references for timing."""

import hashlib
import json
from pathlib import Path
import tempfile

import numpy as np

from export_csr_arduino import array_definition, dense_layer_references, export
from threshold_tools import load_model, load_validation, prune


def generate(root, output):
    root, output = Path(root), Path(output)
    selection = root / "pruning/results/h40/summary.json"
    archive = selection.parent / "selected_csr.npz"
    header = root / "hdjsk/model_parameters.h"
    validation_csv = root / "pruning/validation.csv"
    report = json.loads(selection.read_text())
    with tempfile.TemporaryDirectory(prefix="csr-benchmark-export-") as name:
        generated = Path(name) / "csr.h"
        export(header, selection, archive, validation_csv, generated)
        # Omit the earlier layer-reference self-test arrays from this build.
        csr_text = generated.read_text().split("\n#if ENABLE_CSR_SELF_TEST\n")[0]
    dense = load_model(header)
    sparse = prune(dense, report["selected"]["threshold"])
    validation = load_validation(validation_csv, expected_reads=report["validation_read_count"])
    inputs = validation["inputs"]
    if len(inputs) > np.iinfo(np.uint16).max:
        raise ValueError("Too many fixed inputs for the benchmark index type.")
    text = "// Generated by pruning/export_benchmark_arduino.py.\n" + csr_text
    text += "\n// Dense and CSR share unchanged biases; every model array is const.\n"
    for layer, (weight, _) in enumerate(dense, start=1):
        text += array_definition(f"dense_weight_{layer}", weight.ravel(), "float")
    text += f"\nconstexpr uint16_t BENCHMARK_INPUT_COUNT = {len(inputs)};\n"
    text += f'const char BENCHMARK_INPUT_SHA256[] = "{hashlib.sha256(validation_csv.read_bytes()).hexdigest()}";\n'
    text += array_definition("BENCHMARK_INPUTS", inputs, "float")
    text += array_definition("DENSE_EXPECTED_OUTPUTS", dense_layer_references(dense, inputs)[-1], "float")
    text += array_definition("CSR_EXPECTED_OUTPUTS", dense_layer_references(sparse, inputs)[-1], "float")
    if "CSR_SELF_TEST_INPUTS" in text:
        raise AssertionError("Layer-reference arrays must not enter the timing build.")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding="utf-8")
    return {"inputs": len(inputs), "input_and_check_array_bytes": int(inputs.nbytes * 3),
            "output": str(output)}


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    print(json.dumps(generate(root, root / "hdjsk_benchmark/benchmark_parameters.h"), indent=2))
